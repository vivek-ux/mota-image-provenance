                "class ImportanceGate(nn.Module):\n",
                "    \"\"\"\n",
                "    Two-layer MLP gate to predict patch saliency / importance weights.\n",
                "    \"\"\"\n",
                "    def __init__(self, in_dim=512, hidden_dim=128):\n",
                "        super().__init__()\n",
                "        self.mlp = nn.Sequential(\n",
                "            nn.Linear(in_dim, hidden_dim),\n",
                "            nn.ReLU(),\n",
                "            nn.Dropout(0.2),\n",
                "            nn.Linear(hidden_dim, 1),\n",
                "            nn.Sigmoid()\n",
                "        )\n",
                "        \n",
                "    def forward(self, patch_tokens):\n",
                "        \"\"\"\n",
                "        Args:\n",
                "            patch_tokens: [B, num_tokens, 512]\n",
                "        Returns:\n",
                "            weights: [B, num_tokens, 1]\n",
                "        \"\"\"\n",
                "        weights = self.mlp(patch_tokens)\n",
                "        # Normalize across patches so sum of weights equals 1\n",
                "        weights = weights / (weights.sum(dim=1, keepdim=True) + 1e-8)\n",
                "        return weights\n",
