                "class MultiScalePatchTokenizer:\n",
                "    \"\"\"\n",
                "    Extracts multi-scale local patches to produce patch tokens for an image.\n",
                "    \"\"\"\n",
                "    def __init__(self, mode='dynamic'):\n",
                "        assert mode in ['rigid', 'dynamic'], \"Mode must be 'rigid' or 'dynamic'\"\n",
                "        self.mode = mode\n",
                "\n",
                "    def get_crops(self, pil_img):\n",
                "        w, h = pil_img.size\n",
                "        crops = []\n",
                "        \n",
                "        if self.mode == 'rigid':\n",
                "            # Four 2x2 crops\n",
                "            for i in range(2):\n",
                "                for j in range(2):\n",
                "                    box = (j * w // 2, i * h // 2, (j + 1) * w // 2, (i + 1) * h // 2)\n",
                "                    crops.append(pil_img.crop(box))\n",
                "            # Nine 3x3 crops\n",
                "            for i in range(3):\n",
                "                for j in range(3):\n",
                "                    box = (j * w // 3, i * h // 3, (j + 1) * w // 3, (i + 1) * h // 3)\n",
                "                    crops.append(pil_img.crop(box))\n",
                "            # Total = 13 crops\n",
                "            \n",
                "        elif self.mode == 'dynamic':\n",
                "            # 1. Global image\n",
                "            crops.append(pil_img)\n",
                "            \n",
                "            # 2. Center Anchors (fixes center boundary-crossing)\n",
                "            for scale in [0.66, 0.50]:\n",
                "                cw, ch = int(w * scale), int(h * scale)\n",
                "                x1 = (w - cw) // 2\n",
                "                y1 = (h - ch) // 2\n",
                "                crops.append(pil_img.crop((x1, y1, x1 + cw, y1 + ch)))\n",
                "                \n",
                "            # 3. Overlapping Multi-Scale Grid (50% scale, 3x3 overlapping stride)\n",
                "            crop_sz = int(w * 0.45)\n",
                "            step_x = (w - crop_sz) // 2\n",
                "            step_y = (h - crop_sz) // 2\n",
                "            for i in range(3):\n",
                "                for j in range(3):\n",
                "                    x1 = j * step_x\n",
                "                    y1 = i * step_y\n",
                "                    crops.append(pil_img.crop((x1, y1, x1 + crop_sz, y1 + crop_sz)))\n",
                "            # Total = 1 + 2 + 9 = 12 diverse, boundary-resilient crops\n",
                "            \n",
                "        return crops\n",
